"""Makes ShelfV4/world_map.h: a 128x64 land mask of the world (equirectangular, 180W..180E,
80N..60S: the far north and Antarctica left off, so the lands people live on are bigger) for the screen's sunlit-earth page, from Natural Earth's 1:110m land polygons
(public domain, https://www.naturalearthdata.com).
    curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/110m_physical/ne_110m_land.{shp,shx,dbf}
    python3 tools/gen_worldmap.py ne_110m_land.shp ShelfV4/world_map.h      (needs pyshp and Pillow)
"""
import sys, shapefile
from PIL import Image, ImageDraw
W, H, S = 128, 64, 8
TOP, BOTTOM = 80, -60                      # latitudes of the top and bottom edges                       # drawn 8x larger, then each screen pixel is land if 35% of it is
big = Image.new("L", (W * S, H * S), 0)
d = ImageDraw.Draw(big)
for shp in shapefile.Reader(sys.argv[1]).shapes():
    pts = shp.points; parts = list(shp.parts) + [len(pts)]
    for a, b in zip(parts, parts[1:]):
        d.polygon([((x + 180) / 360 * W * S, (TOP - y) / (TOP - BOTTOM) * H * S) for x, y in pts[a:b]], fill=255)
small = big.resize((W, H), Image.BOX)
rows = []
for y in range(H):
    bits = [1 if small.getpixel((x, y)) >= 90 else 0 for x in range(W)]
    rows.append([sum(bits[i + k] << (7 - k) for k in range(8)) for i in range(0, W, 8)])
out = ["// Generated by tools/gen_worldmap.py from Natural Earth 1:110m land (public domain) -- don't edit.",
       "// 128x64, one bit a pixel (1 = land), left to right from 180W, top to bottom from 80N to 60S.",
       "#define WORLD_TOP 80\n#define WORLD_BOTTOM (-60)",
       "#pragma once", "static const uint8_t WORLD_MAP[64][16] PROGMEM = {"]
out += ["  {" + ",".join(f"0x{b:02x}" for b in r) + "}," for r in rows] + ["};", ""]
open(sys.argv[2], "w").write("\n".join(out))
for y in range(0, H, 2): print("".join("#" if small.getpixel((x, y)) >= 90 else "." for x in range(0, W)))
