"""Builds ShelfV4/daily_gen.h from The Shelf's public/app.js: the same daily affirmations and
colors-of-the-day its Home page shows, so the board's screen shows today's too.
    python3 tools/gen_daily.py <path-to-the-shelf> <out.h>
"""
import json, re, sys, pathlib
src = pathlib.Path(sys.argv[1]) / "public" / "app.js"
js = src.read_text(encoding="utf-8")

def block(name):
    m = re.search(r"const " + name + r" = \[(.*?)\n\];", js, re.S)
    if not m: sys.exit(f"gen_daily: couldn't find {name} in app.js")
    return m.group(1)

def js_strings(text):
    out = []
    for m in re.finditer(r'"((?:[^"\\]|\\.)*)"|\'((?:[^\'\\]|\\.)*)\'', text):
        s = m.group(1) if m.group(1) is not None else m.group(2)
        out.append(json.loads('"' + s.replace('\\\'', "'").replace('"', '\\"') + '"') if m.group(2) is not None else json.loads('"' + s + '"'))
    return out

affs = js_strings(block("AFFIRMATIONS"))
cols = []
for m in re.finditer(r"\{\s*name:\s*'([^']*)',\s*hex:\s*'([^']*)',\s*meaning:\s*'([^']*)'\s*\}", block("DAILY_COLORS")):
    cols.append((m.group(1), m.group(3)))
if len(affs) < 10 or len(cols) < 10:
    sys.exit(f"gen_daily: only found {len(affs)} affirmations and {len(cols)} colors -- app.js changed?")

def c(s):  # C string, ASCII only (the screen's fonts are plain ASCII)
    s = s.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"').replace("—", "-").replace("–", "-")
    s = s.replace("\u2026", "...").encode("ascii", "ignore").decode()
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["// Generated by tools/gen_daily.py from The Shelf's public/app.js -- don't edit.",
       "#pragma once",
       f"static const char* const DAILY_AFFIRMATIONS[{len(affs)}] PROGMEM = {{"]
out += ["  " + c(a) + "," for a in affs] + ["};",
       f"static const char* const DAILY_COLOR_NAMES[{len(cols)}] PROGMEM = {{"]
out += ["  " + c(n) + "," for n, _ in cols] + ["};",
       f"static const char* const DAILY_COLOR_MEANINGS[{len(cols)}] PROGMEM = {{"]
out += ["  " + c(m) + "," for _, m in cols] + ["};", ""]
pathlib.Path(sys.argv[2]).write_text("\n".join(out), encoding="utf-8")
print(f"gen_daily: {len(affs)} affirmations, {len(cols)} colors")
